package com.luoliaoo.wechat.data

/**
 * ★ v10.3.0：**视觉等级** —— 四档提示词，控制识图模型描述图片的详细程度。
 *
 * ═══════════════════════════════════════════════════════════════════════════════
 * 【最重要的一句话：等级改的是提示词，不是模型】
 *
 * 等级**不会**换一个更强的模型。模型由 [Config.visionModel] 决定。
 * 本文件唯一的作用是：按等级返回一段**不同的提示词**，让同一个模型
 * 输出不同详细程度的描述。用户看到"高"时如果以为是换了模型，那是误解 ——
 * 所以 UI 上必须写清"消耗 token 不一样"，而不是暗示"效果更好"。
 *
 * 【为什么分等级：详细程度是一个真实的取舍】
 * 识图的输出会**原样进入主模型的提示词**，所以：
 *   * 描述越长 → 主模型拿到的信息越多 → 但也越贵、越慢；
 *   * 描述越短 → 越省钱 → 但可能漏掉图里的关键文字。
 *
 * 不同场景要的档位完全不同：
 *   * 只想知道"对方发的是什么东西" → 低档就够；
 *   * 分析一张**聊天截图**（图里全是文字）→ 必须高档，否则等于没看；
 *   * 一张信息密集的表格/长截图 → 极高档。
 *
 * 【为什么不让用户自己写提示词】
 * 自己写对多数用户是负担，而且很容易写出让视觉模型**开始分析**的提示词 ——
 * 而"只描述、不分析"是本功能的一条硬底线：识图模型看不到完整对话上下文，
 * 它做的任何判断都会污染主模型（见 [com.luoliaoo.wechat.ai.VisionClient] 的说明）。
 * 用固定的四档，保证每一档都守住这条底线。
 * ═══════════════════════════════════════════════════════════════════════════════
 */
object VisionLevel {

    /** 低：一句话说明这是什么。最省 token。 */
    const val LOW = 0

    /** 中：主要内容 + 关键文字。默认档。 */
    const val MEDIUM = 1

    /** 高：逐字抄录全部文字 + 描述画面细节。 */
    const val HIGH = 2

    /** 极其高：逐字抄录 + 结构还原 + 标注不确定项。最贵。 */
    const val EXTREME = 3

    /** 所有合法等级，按从低到高排列。UI 用它生成选项，避免手写重复列表。 */
    val ALL = listOf(LOW, MEDIUM, HIGH, EXTREME)

    /** 等级的中文名，用于界面显示。 */
    fun name(level: Int): String = when (level) {
        LOW -> "低"
        MEDIUM -> "中"
        HIGH -> "高"
        EXTREME -> "特高"
        else -> "中"
    }

    /**
     * 这一档**大概**会花多少 token 的说明，用于界面提示。
     *
     * ⚠️【刻意不写具体数字】不同服务商、不同图片分辨率、不同模型对同一张图计费差异极大
     * （有的按张数、有的按图片分块数），写一个具体数字必然是错的，
     * 而错的数字比没有数字更糟 —— 用户会据此做决策。
     * 所以这里只给**相对**关系，并明确说明"具体以服务商计费为准"。
     */
    fun costHint(level: Int): String = when (level) {
        LOW -> "消耗最少，适合只想知道「这是什么」"
        MEDIUM -> "消耗适中，日常聊天推荐"
        HIGH -> "消耗较多，适合图里有很多文字要读"
        EXTREME -> "消耗最多，适合信息密集的长截图"
        else -> "消耗适中，日常聊天推荐"
    }

    /** 把任意整数夹取到合法等级，保证运行时永远拿到四档之一。 */
    fun clamp(v: Int): Int = if (v in ALL) v else MEDIUM

    /**
     * 按等级给出提示词。
     *
     * ═══════════════════════════════════════════════════════════════════════════════
     * 【四档共享的硬规则 —— 任何一档都不得删除】
     *
     * 1. **不是图片就直接跳过**（用户明确要求）。见下面对这条的专门说明。
     * 2. **只描述，不分析**。识图模型看不到完整对话，它的任何判断都会污染主模型。
     * 3. **如实描述，看不清就说看不清**。视觉模型对模糊图片会**编造**合理但不存在的内容
     *    （尤其是文字），而编造出的文字会污染整次分析且用户无法察觉。
     *    明确允许"看不清"，是给它一个比编造更安全的出口。
     * 4. **不使用 markdown 语法**（`**`、`#`、代码块）。这段文字会原样拼进主模型提示词，
     *    多余的标记只会浪费 token 并干扰主模型对格式的理解。
     * ═══════════════════════════════════════════════════════════════════════════════
     *
     * 【"不是图片就直接跳过"为什么必须写在提示词里，而不能只靠代码判断】
     * 代码**能**判断微信给的消息类型是不是 `img`（见 `WeChatEnvelope.isImage`），
     * 并且已经在走那条路 —— 用户看到的每一条非图片消息根本不会发起识图请求。
     *
     * 但代码的判断只能到"消息类型"这一层，判断不了**内容**：
     *   * 一张 `.jpg` 文件里可能装着微信自有 `wxgf` 容器（真机实测遇到过），
     *     服务端可能解不开；
     *   * 图片可能已损坏、被截断，或者整张是纯色/纯黑；
     *   * 图片可能只是个二维码、纯占位图，没有任何可描述的内容；
     *   * 用户从其他 App 分享进来的图片可能根本不是图片。
     *
     * 这些情况下，"跳过"比"硬猜"正确得多：硬猜会让主模型拿到一段
     * 与事实无关的描述，从而给出错误的分析；而跳过只损失一张图的信息量。
     *
     * 这也是本文件与 `VisionClient` 的分工：**代码拦掉"明确不是图片的消息"，
     * 提示词拦掉"看起来是图片但实际无法识别的内容"**。两道防线缺一不可。
     */
    fun prompt(level: Int): String = when (clamp(level)) {
        LOW -> LOW_PROMPT
        MEDIUM -> MEDIUM_PROMPT
        HIGH -> HIGH_PROMPT
        else -> EXTREME_PROMPT
    }

    // ── 四档提示词 ────────────────────────────────────────────────────────────

    private val LOW_PROMPT = """
        请用一句话说明这张图片是什么。

        硬性规则：
        1. 如果这不是一张图片，或者你无法看到任何图像内容，只回复：SKIP
        2. 只描述你确实看到的内容。看不清就直说"看不清"，不要猜测或补全。
        3. 不要分析、不要推测意图或心理、不要给建议。
        4. 不要使用 markdown 标记。

        直接输出那一句话，不要加任何前言。
    """.trimIndent()

    private val MEDIUM_PROMPT = """
        请描述这张图片的内容，供后续的聊天分析使用。

        要求：
        1. 说明这是什么类型的图（聊天截图 / 照片 / 表情包 / 海报 / 其他）。
        2. 用一两句话概括主要内容。
        3. 如果图里有文字，抄录其中**关键**的几句（例如对方说了什么、标题、通知正文）。
        4. 如果是表情包或梗图，说明它画的是什么、传达什么情绪。

        硬性规则：
        1. 如果这不是一张图片，或者你无法看到任何图像内容，只回复：SKIP
        2. 只描述你**确实看到**的内容。看不清、拿不准的部分直接说"看不清"，不要猜测或补全。
        3. 不要分析、不要推测对方的意图或心理，也不要给建议。
        4. 不要使用 markdown 标记。

        直接输出描述本身，不要加任何前言。
    """.trimIndent()

    private val HIGH_PROMPT = """
        请详细描述这张图片的内容，供后续的聊天分析使用。

        要求：
        1. 说明这是什么类型的图（聊天截图 / 照片 / 表情包 / 海报 / 文档 / 其他）。
        2. 如果是文字截图（聊天记录、通知、网页、文档等），**逐字准确抄录**其中的文字，
           保留说话人和先后顺序，不要概括、不要省略、不要改写。
        3. 如果是照片，描述：人物（数量、大致动作与表情）、场景、明显物品、以及整体氛围。
        4. 如果是表情包或梗图，说明它画的是什么、传达什么情绪或态度。
        5. 如果有时间戳、人数、金额、数量等数字信息，一并抄录。

        硬性规则：
        1. 如果这不是一张图片，或者你无法看到任何图像内容，只回复：SKIP
        2. 只描述你**确实看到**的内容。看不清、拿不准的部分直接说"看不清"，不要猜测或补全。
        3. 不要分析、不要推测对方的意图或心理，也不要给建议。
        4. 不要使用 markdown 标记。

        直接输出描述本身，不要加任何前言。
    """.trimIndent()

    private val EXTREME_PROMPT = """
        请极其详尽地描述这张图片，供后续的聊天分析使用。

        要求：
        1. 说明这是什么类型的图（聊天截图 / 照片 / 表情包 / 海报 / 文档 / 其他）。
        2. 如果是文字截图，**逐字准确抄录全部可见文字**，并还原结构：
           谁说的、说的先后顺序、哪些是引用、哪些是系统提示。
           不要概括、不要省略、不要改写，宁可冗长也不要遗漏。
        3. 如果有多个画面区域或多个聊天气泡、多个图片区域，请分别说明每一块的内容，
           并指出它们之间的位置关系（上下、左右、嵌套）。
        4. 如果是照片，描述：人物（数量、大致动作、表情、衣着）、场景、
           明显物品、光线与色调、以及整体氛围。
        5. 如果是表情包或梗图，说明它画的是什么、传达什么情绪或态度、以及是否有文字。
        6. 抄录所有数字类信息：时间戳、人数、金额、数量、编号。
        7. 最后单独用一行列出你**看不清或无法确定**的部分。

        硬性规则：
        1. 如果这不是一张图片，或者你无法看到任何图像内容，只回复：SKIP
        2. 只描述你**确实看到**的内容。绝对不要猜测或补全看不清的内容 ——
           宁可写"看不清"也不要给一个可能错误的答案。
        3. 不要分析、不要推测对方的意图或心理，也不要给建议。
        4. 不要使用 markdown 标记。

        直接输出描述本身，不要加任何前言。
    """.trimIndent()

    /**
     * 识图模型表示"这不是图片 / 我看不到内容"时的应答。
     *
     * 见 [prompt] 里第 1 条硬规则。调用方必须**认这个标记**并当作"没有描述"处理 ——
     * 否则字符串 "SKIP" 会被当作图片描述塞进主模型的提示词，
     * 主模型会以为图里写着"SKIP"。
     */
    const val SKIP_TOKEN = "SKIP"

    /** 判断识图模型的回答是否是"请跳过"。容忍大小写与常见的标点包装。 */
    fun isSkip(reply: String?): Boolean {
        val t = reply?.trim()?.trim('.', '。', '"', '\'', '*', '`', '(', ')')?.uppercase()
            ?: return false
        /* 只认**完全等于** SKIP 的回复。
         *
         * 【为什么不做成"包含 SKIP 就算"】那会误伤正常描述：
         * 模型完全可能输出"图里写着 SKIP 字样"这种真实描述，
         * 若按包含判断，这条描述会被丢弃 —— 用户看到的是"图片没被识别"，
         * 而实际上模型看得很清楚。宁可多漏一次跳过（退化成把 "SKIP" 当描述），
         * 也不要误杀一条真实描述。
         *
         * 提示词里要求的就是"只回复：SKIP"，所以完全相等是模型应当给出的形状。 */
        return t == SKIP_TOKEN
    }
}
